"""The tool reference page, generated from the running server (#28).

    python -m simba_mcp.reference            # write docs/tools.md
    python -m simba_mcp.reference --check    # exit 1 when the committed page differs

Every tool the server registers — name, title, whether it reads or writes, its description and its
parameters — rendered from the same objects `tools/list` serves, so the page cannot drift from the
server. It states the tool count and no version, so a release does not change it.
"""

from __future__ import annotations

import argparse
import inspect
import json
import sys
from pathlib import Path
from typing import Any

import anyio

DOCS = Path(__file__).resolve().parents[2] / "docs" / "tools.md"

# Section order and headings, by the module that defines each tool.
SECTIONS = {
    "data": "Data and pipelines",
    "projects": "Projects",
    "models": "Models",
    "results": "Results",
    "scenarios": "Scenarios and optimization",
    "studies": "Studies",
    "recipes": "Study recipes",
    "drafts": "Recipe drafts",
    "quality": "Quality policies, evaluation and decisions",
}


def _type(schema: dict[str, Any]) -> str:
    """A short, readable type for one JSON-schema property."""
    if "anyOf" in schema:
        parts = [_type(s) for s in schema["anyOf"] if s.get("type") != "null"]
        nullable = any(s.get("type") == "null" for s in schema["anyOf"])
        return " \\| ".join(parts) + (" (optional)" if nullable else "")
    kind = schema.get("type")
    if kind == "array":
        return f"list of {_type(schema.get('items', {}))}"
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "enum" in schema:
        return " \\| ".join(json.dumps(v) for v in schema["enum"])
    return kind or "any"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _effect(tool: Any) -> str:
    hints = tool.annotations
    if hints is None:
        return "unspecified"
    if hints.read_only_hint:
        return "reads"
    return "writes, destructive" if hints.destructive_hint else "writes"


def render(tools: list[Any], sections: dict[str, str]) -> str:
    """The Markdown page for ``tools``; ``sections`` maps a tool name to its section key."""
    by_section: dict[str, list[Any]] = {key: [] for key in SECTIONS}
    for tool in sorted(tools, key=lambda t: t.name):
        by_section.setdefault(sections.get(tool.name, "other"), []).append(tool)
    out = [
        "# Tools",
        "",
        "<!-- Generated by `python -m simba_mcp.reference` from the running server. Do not edit by hand. -->",
        "",
        (
            f"The server registers **{len(tools)} tools**. Each entry is what `tools/list` returns: the "
            "tool's name, whether it reads or writes, its description and its parameters. Effects are MCP "
            "annotations — hints for clients, never authorization."
        ),
        "",
    ]
    for key, members in by_section.items():
        if not members:
            continue
        heading = SECTIONS.get(key, key.title())
        out.append(f"- [{heading}](#{_anchor(heading)}) ({len(members)})")
    out.append("")
    for key, members in by_section.items():
        if not members:
            continue
        out += [f"## {SECTIONS.get(key, key.title())}", ""]
        for tool in members:
            out += [f"### `{tool.name}`", ""]
            meta = [f"**{_effect(tool)}**"]
            if tool.title:
                meta.insert(0, tool.title)
            out += [" · ".join(meta), ""]
            description = inspect.cleandoc(tool.description or "")
            if description:
                out += [description, ""]
            props = (tool.input_schema or {}).get("properties", {})
            required = set((tool.input_schema or {}).get("required", []))
            if props:
                out += ["| Parameter | Type | Required | Default |", "|---|---|---|---|"]
                for name, schema in props.items():
                    default = (
                        "" if "default" not in schema else f"`{json.dumps(schema['default'])}`"
                    )
                    out.append(
                        f"| `{name}` | {_cell(_type(schema))} | {'yes' if name in required else ''} | "
                        f"{default} |"
                    )
                out.append("")
            else:
                out += ["No parameters.", ""]
    return "\n".join(out).rstrip("\n") + "\n"


def _anchor(heading: str) -> str:
    return "".join(c for c in heading.lower().replace(" ", "-") if c.isalnum() or c == "-")


def current() -> str:
    """The page for the tools this server registers right now."""
    from simba_mcp.server import TOOLS, mcp

    tools = anyio.run(mcp.list_tools)
    sections = {fn.__name__: fn.__module__.rsplit(".", 1)[-1] for fn in TOOLS}
    return render(tools, sections)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docs/tools.md from the running server.")
    parser.add_argument(
        "--check", action="store_true", help="exit 1 when docs/tools.md is out of date"
    )
    args = parser.parse_args(argv)
    page = current()
    if args.check:
        committed = DOCS.read_text(encoding="utf-8") if DOCS.exists() else ""
        if committed != page:
            print(
                "docs/tools.md is out of date: run `python -m simba_mcp.reference`", file=sys.stderr
            )
            return 1
        print("docs/tools.md is current")
        return 0
    DOCS.write_text(page, encoding="utf-8", newline="\n")
    print(f"wrote {DOCS}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
